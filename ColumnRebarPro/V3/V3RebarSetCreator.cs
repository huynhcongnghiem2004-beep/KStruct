        internal static void CreateLongitudinalSets(Document doc, V3SegmentWork item,
            RebarBarType type, V3BuildReport report)
        {
            V3LegacySplice.ValidateForCreation(item.Config);
            if (item.Config.Splice != V3SpliceStyle.None || item.Config.StaggerSplices ||
                item.HasNext || item.HasPrevious || item.TransitionUp != null ||
                item.TransitionDown != null)
                throw new InvalidOperationException("Không thể tạo nối chồng hoặc chuyển tiếp tự động. Cần chi tiết cấu tạo được thiết kế và duyệt.");
            V3Geometry g = item.Geometry;
            V3RebarConfig c = item.Config;
            double inset = V3Units.Ft(c.Cover + c.TieDiameter + c.MainDiameter / 2);
            double hx = g.Width / 2 - inset, hy = g.Depth / 2 - inset;
            double low = g.Bottom + V3Units.Ft(c.Cover + c.MainDiameter / 2);
            double high = g.Top - V3Units.Ft(c.Cover + c.MainDiameter / 2);

            if (c.StarterBars) high = Math.Max(high, g.Top + V3Units.Ft(c.StarterLength));
            // V4: create from actual design curves using project Shapes. No manual selection.

            CreateStraightArray(doc, item, type, g.At(-hx, -hy, 0), g.X,
                hx * 2, c.Cx, low, high, report);
            CreateStraightArray(doc, item, type, g.At(-hx, hy, 0), g.X,
                hx * 2, c.Cx, low, high, report);

            int interior = c.Cy - 2;
            if (interior > 0)
            {
                double step = 2 * hy / (c.Cy - 1);
                // Exclude the four corners: already generated by the two Cx groups.
                CreateStraightArray(doc, item, type, g.At(-hx, -hy + step, 0), g.Y,
                    step * (interior - 1), interior, low, high, report);
                CreateStraightArray(doc, item, type, g.At(hx, -hy + step, 0), g.Y,
                    step * (interior - 1), interior, low, high, report);
            }
        }

        private static void CreateStraightArray(Document doc, V3SegmentWork item,
            RebarBarType type, XYZ basePoint, XYZ normal, double length,
            int count, double low, double high, V3BuildReport report)
        {
            if (count <= 0) return;
            XYZ a = new XYZ(basePoint.X, basePoint.Y, low);
            XYZ b = new XYZ(basePoint.X, basePoint.Y, high);
            XYZ widthAxis=normal.CrossProduct(XYZ.BasisZ).Normalize();
            XYZ xVector=XYZ.BasisZ*(high-low);
            XYZ yVector=widthAxis*type.BarNominalDiameter;
            Rebar rebar = V4AutomaticRebar.Create(doc, RebarStyle.Standard, type,
                item.Column, normal, V4AutomaticRebar.Lines(a, b),
                null, null, item.Column.Id, "thanh dọc");
            V3RebarShapeFactory.ValidateEnvelope(rebar, new[] { a, b }, V3Units.Ft(2),
                item.Column.Id, "thanh dọc");
            V3RebarBuilder.SetPartition(rebar, V3RebarBuilder.Partition(item.Column.Id));
            if (count >= 2)
            {
                ApplyFixedNumber(rebar, count, length, "thép dọc");
                V3RebarShapeFactory.ValidateLayout(rebar, count, length, normal,
                    item.Column.Id, "thép dọc");
                report.MainSets++;
            }
            report.MainBars += count;
        }

        internal static List<V3AnchorArray> AnchorPlan(V3SegmentWork item)
        {
            var c = item.Config;
            return V3AnchorLayoutPlan.Create(c.Cx, c.Cy, V3Units.Mm(item.Geometry.Width),
                V3Units.Mm(item.Geometry.Depth), c.Cover, c.TieDiameter, c.MainDiameter,
                item.FoundationHost == null ? V3AnchorDirection.Inward : c.FoundationAnchorDirection);
        }

        internal static void CreateShapedLongitudinalSets(Document doc, V3SegmentWork item,
            RebarBarType type, V3BuildReport report)
        {
            var g=item.Geometry;var c=item.Config;
            if(item.BottleneckToUpper)type=V3BottleneckBarType.Resolve(doc,type,c);
            double radius=(V3Units.Mm(type.StandardBendDiameter)+c.MainDiameter)/2;
            double tolerance=V3Units.Mm(doc.Application.ShortCurveTolerance);
            var paths=ConnectionPaths(item);
            var groups=V3ProfileGeometry.Group(paths,c.GroupLongBars);
            if(item.BottleneckToUpper &&
                (item.ConnectionPlan.UnmatchedLower.Count>0 || item.ConnectionPlan.UnmatchedUpper.Count>0))
                report.Warnings.Add("Tầng " + item.Segment.LevelName + " → " + item.ConnectionPlan.Upper.Label +
                    ": ghép " + item.ConnectionPlan.Bars.Count + " cặp; " + item.ConnectionPlan.UnmatchedLower.Count +
                    " thanh dư dưới dừng trước mạch ngừng, " + item.ConnectionPlan.UnmatchedUpper.Count +
                    " thanh dư trên bắt đầu sau cover. Phải kiểm tra và duyệt chi tiết neo/cắt, cốt đai nút và khả năng thi công trước khi phát hành.");
            // The project Shape for each anchor path is determined from curves.
            foreach(var group in groups)
            {
                var path=group.Bars[0];
                var rounded=V3ProfileGeometry.Round(path.Points,radius,tolerance);
                if(item.BottleneckToUpper&&!path.Unmatched)
                {
                    double lapStart=Math.Max(V3Units.Mm(item.BottleneckUpperBarStart),rounded.Last().Start.Z);
                    double minimum=V3BottleneckRules.MinimumLap(Math.Max(c.MainDiameter,item.ConnectionPlan.Upper.Diameter));
                    if(rounded.Last().End.Z-lapStart<minimum-.1)
                        throw new InvalidOperationException("Thanh "+(path.BarIndex+1)+": đoạn nối thẳng sau gối uốn không đủ chiều dài tối thiểu.");
                }
                if(!path.Planar)
                    throw new InvalidOperationException("Thanh "+(path.BarIndex+1)+": đường nhiều mặt phẳng chưa hỗ trợ bằng Rebar Shape có sẵn. Lệnh không tạo FreeForm hoặc shape mới.");
                // A bar plane must be inferred from the actual design legs.
                // The array step is a distribution direction, never the definition of the bar plane.
                var distribution = group.Bars.Count > 1 ? (V3Point3?)group.Step : null;
                V3Point3 planeNormal = V4AnchorGeometry.PlaneNormal(path.Points, distribution,
                    Math.Max(0.1, tolerance));
                var target=path.Points.Select(ModelPoint).ToList();
                XYZ firstDirection=(target[1]-target[0]).Normalize();
                var roundedEnvelope=rounded.SelectMany(curve => curve.Arc
                    ? new[] { curve.Start, curve.Mid, curve.End }
                    : new[] { curve.Start, curve.End }).Select(ModelPoint).ToList();
                XYZ normal=ModelVector(planeNormal).Normalize();
                XYZ secondAxis=normal.CrossProduct(firstDirection).Normalize();
                V3RebarShapeFactory.GetBox(roundedEnvelope,firstDirection,secondAxis,type.BarNominalDiameter,
                    out XYZ boxOrigin,out XYZ xVector,out XYZ yVector);
                // Revit CreateFromCurves expects the unrounded design legs.
                // Revit calculates bends from RebarBarType; the rounded envelope
                // below remains the independent geometric acceptance check.
                IList<Curve> shapeCurves = V4AutomaticRebar.Lines(target.ToArray());
                Rebar bar = V4AutomaticRebar.Create(doc, RebarStyle.Standard, type,
                    item.FoundationHost ?? (Element)item.Column, normal, shapeCurves,
                    null, null, item.Column.Id, "thanh neo/chuyển tiếp",
                    allowNewShape: true);
                V3RebarShapeFactory.ValidateEnvelope(bar,roundedEnvelope,V3Units.Ft(2),item.Column.Id,"thanh neo/chuyển tiếp");
                if(group.Bars.Count>1)
                {
                    double arrayLength=V3Units.Ft(group.Step.Length*(group.Bars.Count-1));
                    ApplyFixedNumber(bar,group.Bars.Count,arrayLength,"thép chuyển tiếp");
                    V3RebarShapeFactory.ValidateLayout(bar,group.Bars.Count,arrayLength,normal,
                        item.Column.Id,"thép chuyển tiếp");
                    report.MainSets++;
                }
                V3RebarBuilder.SetPartition(bar,item.Column.Id);doc.Regenerate();
                if(item.BottleneckToUpper)V3BottleneckBarType.CheckBends(bar,c,rounded.Count(r=>r.Arc));
                V3RebarShapeFactory.ValidateLayout(bar,group.Bars.Count,
                    group.Bars.Count>1?V3Units.Ft(group.Step.Length*(group.Bars.Count-1)):0,
                    normal,item.Column.Id,"thép chuyển tiếp");
                report.MainBars+=group.Bars.Count;
            }

        }

        private static XYZ ModelPoint(V3Point3 p)=>new XYZ(V3Units.Ft(p.X),V3Units.Ft(p.Y),V3Units.Ft(p.Z));
        private static XYZ ModelVector(V3Point3 p)=>new XYZ(V3Units.Ft(p.X),V3Units.Ft(p.Y),V3Units.Ft(p.Z));

        internal static List<V3BarPath> ConnectionPaths(V3SegmentWork item)
        {
            var g=item.Geometry;var c=item.Config;var result=new List<V3BarPath>();
            double low=item.FoundationHost==null?V3Units.Mm(g.Bottom)+c.Cover+c.MainDiameter/2:V3Units.Mm(item.FoundationBendZ);
            double high=c.StarterBars?V3Units.Mm(g.Top)+c.StarterLength:V3Units.Mm(g.Top)-c.Cover-c.MainDiameter/2;
            double footLength=item.FoundationHost==null?0:V3AnchorLayoutPlan.HorizontalLength(item.FoundationAnchorLengthMm,
                V3Units.Mm(g.Bottom-item.FoundationBendZ));
            foreach(var array in AnchorPlan(item))for(int i=0;i<array.Count;i++)
            {
                XYZ model=g.At(V3Units.Ft(array.X+array.StepX*i),V3Units.Ft(array.Y+array.StepY*i),0);
                var xy=new V3Point2(V3Units.Mm(model.X),V3Units.Mm(model.Y));
                var path=new V3BarPath{BarIndex=result.Count,Points=new List<V3Point3>()};
                if(item.FoundationHost!=null)
                    path.Points.Add(new V3Point3(xy.X+(g.X.X*array.HookX+g.Y.X*array.HookY)*footLength,
                        xy.Y+(g.X.Y*array.HookX+g.Y.Y*array.HookY)*footLength,low));
                path.Points.Add(new V3Point3(xy.X,xy.Y,low));
                if(item.BottleneckToUpper)
                {
                    var connection=item.ConnectionPlan.Bars.SingleOrDefault(p=>(p.Lower-xy).Length<.05);
                    if(connection==null)
                    {
                        if(!item.ConnectionPlan.UnmatchedLowerPoints.Any(p=>(p-xy).Length<.05))
                            throw new InvalidOperationException("Không xác định được cặp hoặc trạng thái thanh dư ở tầng dưới.");
                        path.Unmatched=true;
                        double stop=V3Units.Mm(g.Top)-c.Cover-c.TieDiameter-c.MainDiameter/2;
                        if(stop<=low+V3Units.Mm(2))throw new InvalidOperationException("Không đủ chiều cao để kết thúc thanh dư trước mạch ngừng theo lớp bảo vệ.");
                        path.Points.Add(new V3Point3(xy.X,xy.Y,stop));
                    }
                    else
                    {
                        path.BarIndex=connection.LowerIndex;path.Shift=connection.Shift;path.Height=connection.Height;
                        if(connection.Shift>.001)
                        {
                            path.Points.Add(new V3Point3(xy.X,xy.Y,V3Units.Mm(g.Top)-connection.Height));
                            path.Points.Add(new V3Point3(connection.End.X,connection.End.Y,V3Units.Mm(g.Top)));
                        }
                        path.Points.Add(new V3Point3(connection.End.X,connection.End.Y,high));
                    }
                }
                else path.Points.Add(new V3Point3(xy.X,xy.Y,high));
                result.Add(path);
            }
            return result;
        }

        internal static List<V3TieBand> TiePlan(V3SegmentWork item)
        {
            var c = item.Config;
            return V3TieLayoutPlan.Create(V3Units.Mm(item.Geometry.Height), c.Cover, c.TieDiameter,
                c.EndZone, c.EndSpacing, c.MidSpacing, c.TieLayout == V3TieLayout.FixedNumber,
                c.EndTieCount, c.MidTieCount, false, 0, 0);
        }

        internal static void CreateTies(Document doc, V3SegmentWork item,
            RebarBarType type, RebarHookType hook135, RebarHookType hook90, V3BuildReport report)
        {
            var g = item.Geometry;
            var c = item.Config;
            if (!c.GroupTies || c.TieLayout != V3TieLayout.MaximumSpacing)
                throw new InvalidOperationException("Thép đai bắt buộc dùng Rebar Set Maximum Spacing.");
            double inset = V3Units.Ft(c.Cover + c.TieDiameter / 2);
            double tx = g.Width / 2 - inset, ty = g.Depth / 2 - inset;
            int level = 0;
            // No hard-coded RebarShape ID: Revit matches the project library using curves.
            // The operator controls whether ties continue through framing joints.
            // Excluding positions is never inferred as an engineering requirement.
            var exclusions = c.ShowJointTies
                ? new List<Tuple<double, double>>()
                : V4TieJointExclusion.Find(doc, item);
            var plannedBands = TiePlan(item);
            var safeBands = V4TieBandExclusion.KeepOutside(plannedBands, exclusions);
            V4TieBandExclusion.RequireAtLeastOneTie(plannedBands, safeBands);
            if (safeBands.Any(b => b.Count < 2))
                throw new InvalidOperationException("Cột " + item.Column.Id.Value +
                    ": vùng giao làm còn một đai đơn lẻ; không thể tạo Rebar Set Maximum Spacing. " +
                    "Điều chỉnh phạm vi/bước đai theo thiết kế thay vì tạo Single hoặc Fixed Number.");
            foreach (var band in safeBands)
            {
                double z = g.Bottom + V3Units.Ft(band.Start);
                double length = V3Units.Ft(band.End - band.Start);
                if (c.GroupTies && band.Count >= 2)
                {
                    Rebar outer = CreateOuter(doc, item, type, hook135, tx, ty, z);
                    ApplyBand(outer, band, length);
                    ValidateMaxSpacing(outer, length, band.MaximumSpacing, XYZ.BasisZ,
                        item.Column.Id, "đai bao");
                    report.TieSets++;
                    report.Ties += outer.NumberOfBarPositions;
                }
                else
                {
                    for (int i = 0; i < band.Count; i++)
                    {
                        CreateOuter(doc, item, type, hook135, tx, ty,
                            g.Bottom + V3Units.Ft(band.Position(i)));
                        report.Ties++;
                    }
                }
                if (c.CrossTies)
                {
                    if (c.GroupTies && !c.CrossTiesAlternating)
                        CreateCrossLevel(doc, item, type, hook135, hook135, tx, ty, z,
                            band.Count, length, band.MaximumSpacing, false, report);
                    else if (c.GroupTies)
                    {
                        // Two interleaved sets preserve alternation along height, including zone boundaries.
                        for (int parity = 0; parity < 2 && parity < band.Count; parity++)
                        {
                            int count = (band.Count - parity + 1) / 2;
                            double first = band.Position(parity);
                            double last = band.Position(parity + 2 * (count - 1));
                            CreateCrossLevel(doc, item, type, hook135, hook90, tx, ty,
                                g.Bottom + V3Units.Ft(first), count, V3Units.Ft(last - first),
                                band.MaximumSpacing * 2, (level + parity) % 2 == 1, report);
                        }
                    }
                    else
                        for (int i = 0; i < band.Count; i++)
                            CreateCrossLevel(doc, item, type, hook135,
                                c.CrossTiesAlternating ? hook90 : hook135, tx, ty,
                                g.Bottom + V3Units.Ft(band.Position(i)), 1, 0,
                                band.MaximumSpacing, c.CrossTiesAlternating && (level + i) % 2 == 1, report);
                }
                level += band.Count;
            }
        }

        private static void ApplyBand(Rebar bar, V3TieBand band, double length)
        {
            if (band.FixedNumber || band.Count < 2)
                throw new InvalidOperationException("Thép đai chỉ cho phép Maximum Spacing; Rebar Set cần ít nhất hai vị trí.");
            // Revit may choose fewer positions than the planner expects for a
            // Maximum Spacing set. Re-measure the actual set and tighten the
            // spacing input until the resulting center-to-center distance
            // meets the design limit. Keep the native Maximum Spacing rule;
            // never silently switch to Fixed Number.
            double appliedSpacingMm = band.MaximumSpacing;
            for (int attempt = 0; attempt < 8; attempt++)
            {
                using (var accessor = bar.GetShapeDrivenAccessor())
                    accessor.SetLayoutAsMaximumSpacing(V3Units.Ft(appliedSpacingMm), length,
                        true, true, true);
                bar.Document.Regenerate();

                int count = bar.NumberOfBarPositions;
                if (count < 2 || count > 1002)
                    throw new InvalidOperationException("Revit tạo số vị trí đai không hợp lệ khi hiệu chỉnh Maximum Spacing.");
                double actualSpacingMm;
                using (var accessor = bar.GetShapeDrivenAccessor())
                {
                    XYZ first = accessor.GetBarPositionTransform(0).Origin;
                    XYZ last = accessor.GetBarPositionTransform(count - 1).Origin;
                    actualSpacingMm = V3Units.Mm(first.DistanceTo(last)) / (count - 1);
                }
                if (actualSpacingMm <= band.MaximumSpacing + .1)
                    return;

                double nextSpacingMm = appliedSpacingMm * band.MaximumSpacing / actualSpacingMm * .9;
                if (nextSpacingMm <= .1 || nextSpacingMm >= appliedSpacingMm)
                    break;
                appliedSpacingMm = nextSpacingMm;
            }
            throw new InvalidOperationException("Không thể hiệu chỉnh Rebar Set để bước đai thực tế nằm trong Maximum Spacing thiết kế.");
            // Never silently switch to Fixed Number even if Revit returns a
            // different number of placements from the preview/planner.
        }

        private static void ValidateMaxSpacing(Rebar bar, double length,
            double requestedMm, XYZ direction, ElementId columnId, string group)
        {
            var layout = bar.get_Parameter(BuiltInParameter.REBAR_ELEM_LAYOUT_RULE);
            if (layout == null || layout.AsInteger() != (int)RebarLayoutRule.MaximumSpacing)
                throw new InvalidOperationException("Cột " + columnId.Value + ": " + group +
                    " không có Layout Rule = Maximum Spacing.");
            int count = bar.NumberOfBarPositions;
            if (count < 2 || count > 1002)
                throw new InvalidOperationException("Cột " + columnId.Value +
                    ": số vị trí Rebar Set " + group + " không hợp lệ.");
            using (var accessor = bar.GetShapeDrivenAccessor())
            {
                XYZ first = accessor.GetBarPositionTransform(0).Origin;
                XYZ last = accessor.GetBarPositionTransform(count - 1).Origin;
                XYZ delta = last - first;
                if (Math.Abs(delta.GetLength() - length) > V3Units.Ft(2) ||
                    Math.Abs(Math.Abs(delta.Normalize().DotProduct(direction.Normalize())) - 1) > 1e-4)
                    throw new InvalidOperationException("Cột " + columnId.Value +
                        ": " + group + " sai chiều dài/hướng Rebar Set.");
                double spacing = delta.GetLength() / (count - 1);
                if (spacing > V3Units.Ft(requestedMm + .1))
                    throw new InvalidOperationException("Cột " + columnId.Value +
                        ": bước đai của " + group + " là " + V3Units.Mm(spacing).ToString("0.##") +
                        " mm, vượt Maximum Spacing " + requestedMm.ToString("0.##") +
                        " mm (" + count + " vị trí trên " + V3Units.Mm(delta.GetLength()).ToString("0.##") + " mm).");
                for (int i = 1; i < count; i++)
                {
                    XYZ expected = first + delta * ((double)i / (count - 1));
                    if (accessor.GetBarPositionTransform(i).Origin.DistanceTo(expected) > V3Units.Ft(2))
                        throw new InvalidOperationException("Cột " + columnId.Value +
                            ": " + group + " có vị trí đai không đúng khoảng cách.");
                }
            }
        }

        private static Rebar CreateOuter(Document doc, V3SegmentWork item,
            RebarBarType type, RebarHookType hook, double tx, double ty, double z)
        {
            V3Geometry g = item.Geometry;
            V3RebarConfig c = item.Config;
            XYZ[] points = { g.At(-tx,-ty,z), g.At(tx,-ty,z), g.At(tx,ty,z),g.At(-tx,ty,z) };
            RebarHookType h = c.TieStyle == V3TieStyle.Hook135 ? hook : null;
            XYZ origin=g.At(-tx,-ty,z);
            XYZ xVector=g.X*(2*tx), yVector=g.Y*(2*ty);
            Rebar bar = V4AutomaticRebar.Create(doc, RebarStyle.StirrupTie, type,
                item.Column, g.X.CrossProduct(g.Y),
                V4AutomaticRebar.Lines(points[0], points[1], points[2], points[3], points[0]),
                h, h, item.Column.Id, "đai bao");
            V3RebarShapeFactory.ValidateEnvelope(bar,points,V3Units.Ft(2),item.Column.Id,"đai bao");
            V3RebarBuilder.SetPartition(bar, V3RebarBuilder.Partition(item.Column.Id));
            return bar;
        }

        private static void CreateCrossLevel(Document doc, V3SegmentWork item,
            RebarBarType type, RebarHookType startHook, RebarHookType endHook,
            double tx, double ty, double z, int count, double length, double spacingMm, bool reverse,
            V3BuildReport report)
        {
            var g = item.Geometry;
            var c = item.Config;
            double inset = V3Units.Ft(c.Cover + c.TieDiameter + c.MainDiameter / 2);
            for (int i = 1; i < c.Cx - 1; i++)
            {
                double x = -(g.Width / 2 - inset) + (g.Width - 2 * inset) * i / (c.Cx - 1);
                CreateCross(doc, item, type, startHook, endHook, g.At(x, -ty, z), g.At(x, ty, z),
                    count, length, spacingMm, reverse, report);
            }
            for (int i = 1; i < c.Cy - 1; i++)
            {
                double y = -(g.Depth / 2 - inset) + (g.Depth - 2 * inset) * i / (c.Cy - 1);
                CreateCross(doc, item, type, startHook, endHook, g.At(-tx, y, z), g.At(tx, y, z),
                    count, length, spacingMm, reverse, report);
            }
        }

        private static void CreateCross(Document doc, V3SegmentWork item,
            RebarBarType type, RebarHookType startHook, RebarHookType endHook,
            XYZ a, XYZ b, int count, double length, double spacingMm, bool reverse, V3BuildReport report)
        {
            if (startHook == null || endHook == null)
                throw new InvalidOperationException("Thiếu loại móc đai phụ theo cấu hình.");
            if (count < 2)
                throw new InvalidOperationException("Đai phụ còn một vị trí, không thể là Rebar Set Maximum Spacing; " +
                    "cần điều chỉnh phân bố đai phụ đã duyệt.");
            if (reverse) { var temp = a; a = b; b = temp; }
            XYZ direction=(b-a).Normalize();
            XYZ second=Math.Abs(direction.DotProduct(item.Geometry.Y))>.5
                ? item.Geometry.X : item.Geometry.Y;
            XYZ xVector=direction*a.DistanceTo(b);
            double hookExtent=2*Math.Max(type.GetHookLength(startHook.Id),type.GetHookLength(endHook.Id));
            if(hookExtent<=1e-6)
                throw new InvalidOperationException("Không xác định được kích thước Hook cho đai phụ; không thể ScaleToBox an toàn.");
            XYZ scaleOrigin=a-second*(hookExtent/2);
            XYZ yVector=second*hookExtent;
            var bar = V4AutomaticRebar.Create(doc, RebarStyle.StirrupTie, type,
                item.Column, direction.CrossProduct(second),
                V4AutomaticRebar.Lines(a, b), startHook, endHook,
                item.Column.Id, "đai phụ/cross-tie");
            V3RebarShapeFactory.ValidateEnvelope(bar,new[] { scaleOrigin, scaleOrigin+xVector,
                scaleOrigin+yVector, scaleOrigin+xVector+yVector },
                V3Units.Ft(2),item.Column.Id,"đai phụ/cross-tie");
            V3RebarShapeFactory.ValidateAxis(bar,direction,item.Column.Id,"đai phụ/cross-tie");
            double minZ=item.Geometry.Bottom+V3Units.Ft(item.Config.Cover);
            double maxZ=item.Geometry.Top+V3Units.Ft(item.Config.JointBeamHeight+item.Config.StarterLength);
            V3RebarShapeFactory.ValidateInside(bar,item.Geometry,minZ,maxZ,
                V3Units.Ft(item.Config.Cover),item.Column.Id,"đai phụ/cross-tie");
            V3RebarBuilder.SetPartition(bar, item.Column.Id);
            if (count >= 2)
            {
                using (var accessor = bar.GetShapeDrivenAccessor())
                    accessor.SetLayoutAsMaximumSpacing(V3Units.Ft(spacingMm), length,
                        true, true, true);
                ValidateMaxSpacing(bar, length, spacingMm, XYZ.BasisZ,
                    item.Column.Id, "đai phụ/cross-tie");
                report.CrossTieSets++;
            }
            report.CrossTies += count < 2 ? 1 : bar.NumberOfBarPositions;
        }

        private static void ApplyFixedNumber(Rebar rebar, int count, double length, string description)
        {
            if (count < 2 || length <= V3Units.Ft(.1))
                throw new InvalidOperationException("Rebar Set " + description + " cần ít nhất 2 vị trí và chiều dài phân bố dương.");
            try
            {
                using (RebarShapeDrivenAccessor accessor = rebar.GetShapeDrivenAccessor())
                    accessor.SetLayoutAsFixedNumber(count, length, true, true, true);
            }
            catch (Exception ex)
            {
                throw new InvalidOperationException("Không thể thiết lập Fixed Number cho " + description +
                    ". Kiểm tra Shape-Driven Rebar trong Project: " + ex.Message,ex);
            }
        }

